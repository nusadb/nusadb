//! A sequence that has run out reports `2200H` (`sequence_generator_limit_exceeded`) on every path
//! that draws from it, and a `setval` outside its bounds reports `22003`. The `.slt` corpus
//! (`slt/p5_advanced/sequence_limits.slt`) pins the messages; it can only match error text, and a
//! driver branches on the code.

#![allow(
    clippy::expect_used,
    clippy::panic,
    reason = "integration test outside a #[cfg(test)] module"
)]

use nusadb_btree::BtreeEngine;
use nusadb_core::{StorageEngine, TableSchema};
use nusadb_sql::ast::{Statement, Value};
use nusadb_sql::{Catalog, ExecutionResult, Session, analyze, copy_from, parse, plan};

struct EngineCatalog<'a>(&'a dyn StorageEngine);

impl Catalog for EngineCatalog<'_> {
    nusadb_test_utils::catalog_answers_as_superuser!(nusadb_sql);
    fn lookup_table(&self, name: &str) -> Result<Option<TableSchema>, nusadb_sql::Error> {
        self.0.lookup_table(name).map_err(Into::into)
    }
}

fn run(
    session: &mut Session,
    engine: &dyn StorageEngine,
    sql: &str,
) -> Result<ExecutionResult, nusadb_sql::Error> {
    let logical = analyze(parse(sql)?, &EngineCatalog(engine))?;
    session.execute(plan(logical))
}

fn ok(session: &mut Session, engine: &dyn StorageEngine, sql: &str) -> ExecutionResult {
    run(session, engine, sql).unwrap_or_else(|e| panic!("{sql}: {e}"))
}

/// The SQLSTATE `sql` is refused with.
fn code(session: &mut Session, engine: &dyn StorageEngine, sql: &str) -> &'static str {
    match run(session, engine, sql) {
        Ok(result) => panic!("{sql} succeeded: {result:?}"),
        Err(e) => e.sqlstate(),
    }
}

/// The single integer `sql` returns.
fn int(session: &mut Session, engine: &dyn StorageEngine, sql: &str) -> i64 {
    let ExecutionResult::Rows { rows, .. } = ok(session, engine, sql) else {
        panic!("{sql} returned no rows");
    };
    match rows.first().and_then(|row| row.first()) {
        Some(Value::Int(n)) => *n,
        other => panic!("{sql}: unexpected value {other:?}"),
    }
}

#[test]
fn an_exhausted_sequence_is_2200h_on_every_path() {
    let engine = BtreeEngine::new();
    let mut s = Session::new(&engine);
    ok(&mut s, &engine, "CREATE SEQUENCE up MAXVALUE 1");
    ok(&mut s, &engine, "SELECT nextval('up')");
    assert_eq!(code(&mut s, &engine, "SELECT nextval('up')"), "2200H");
    ok(
        &mut s,
        &engine,
        "CREATE SEQUENCE down INCREMENT -1 MINVALUE 0 MAXVALUE 0 START 0",
    );
    ok(&mut s, &engine, "SELECT nextval('down')");
    assert_eq!(code(&mut s, &engine, "SELECT nextval('down')"), "2200H");

    ok(&mut s, &engine, "CREATE TABLE t (id SERIAL, v INT)");
    ok(&mut s, &engine, "ALTER SEQUENCE t_id_seq MAXVALUE 1");
    ok(&mut s, &engine, "INSERT INTO t (v) VALUES (1)");
    for sql in [
        "INSERT INTO t (v) VALUES (2)",
        "INSERT INTO t (v) SELECT 2",
        "INSERT INTO t (v) VALUES (2) ON CONFLICT DO NOTHING",
        "UPDATE t SET id = DEFAULT",
        "MERGE INTO t USING (SELECT 2 AS k) src ON false WHEN NOT MATCHED THEN INSERT (v) VALUES (src.k)",
        "DO $$ BEGIN INSERT INTO t (v) VALUES (2); END $$",
    ] {
        assert_eq!(code(&mut s, &engine, sql), "2200H", "{sql}");
    }

    let Statement::Copy(copy) = parse("COPY t (v) FROM STDIN").expect("parse copy") else {
        panic!("expected COPY");
    };
    let err = copy_from(&engine, &copy, "2\n3\n").expect_err("the sequence is exhausted");
    assert_eq!(err.sqlstate(), "2200H", "{err}");
    assert_eq!(
        err.to_string(),
        "nextval: reached maximum value of sequence \"t_id_seq\" (1)"
    );
    assert_eq!(int(&mut s, &engine, "SELECT count(*) FROM t"), 1);
}

#[test]
fn an_identity_column_stops_at_its_types_maximum() {
    let engine = BtreeEngine::new();
    let mut s = Session::new(&engine);
    ok(
        &mut s,
        &engine,
        "CREATE TABLE small_id (id SMALLINT GENERATED BY DEFAULT AS IDENTITY, v INT)",
    );
    ok(&mut s, &engine, "SELECT setval('small_id_id_seq', 32767)");
    // The sequence refuses the next value; the column's range check is never reached (23514).
    assert_eq!(
        code(&mut s, &engine, "INSERT INTO small_id (v) VALUES (1)"),
        "2200H"
    );
    ok(
        &mut s,
        &engine,
        "CREATE TABLE int_id (id INT GENERATED ALWAYS AS IDENTITY, v INT)",
    );
    ok(
        &mut s,
        &engine,
        "SELECT setval('int_id_id_seq', 2147483647)",
    );
    assert_eq!(
        code(&mut s, &engine, "INSERT INTO int_id (v) VALUES (1)"),
        "2200H"
    );
}

#[test]
fn setval_outside_the_bounds_is_22003_and_changes_nothing() {
    let engine = BtreeEngine::new();
    let mut s = Session::new(&engine);
    ok(&mut s, &engine, "CREATE SEQUENCE b MINVALUE 1 MAXVALUE 10");
    assert_eq!(int(&mut s, &engine, "SELECT nextval('b')"), 1);
    assert_eq!(code(&mut s, &engine, "SELECT setval('b', 11)"), "22003");
    assert_eq!(code(&mut s, &engine, "SELECT setval('b', 0)"), "22003");
    assert_eq!(int(&mut s, &engine, "SELECT nextval('b')"), 2);
    assert_eq!(int(&mut s, &engine, "SELECT setval('b', 10)"), 10);
    assert_eq!(code(&mut s, &engine, "SELECT nextval('b')"), "2200H");
}

#[test]
fn a_cycling_sequence_wraps_instead_of_failing() {
    let engine = BtreeEngine::new();
    let mut s = Session::new(&engine);
    ok(&mut s, &engine, "CREATE SEQUENCE c MAXVALUE 2 CYCLE");
    let values: Vec<i64> = (0..5)
        .map(|_| int(&mut s, &engine, "SELECT nextval('c')"))
        .collect();
    assert_eq!(values, [1, 2, 1, 2, 1]);
}

/// Draw from `seq` until it refuses, returning the last value handed out and the refusal.
fn draw_until_refused(
    s: &mut Session,
    engine: &dyn StorageEngine,
    seq: &str,
) -> (i64, nusadb_sql::Error) {
    let mut last = 0;
    for _ in 0..100 {
        match run(s, engine, &format!("SELECT nextval('{seq}')")) {
            Ok(ExecutionResult::Rows { rows, .. }) => match rows.first().and_then(|r| r.first()) {
                Some(Value::Int(n)) => last = *n,
                other => panic!("unexpected value {other:?}"),
            },
            Ok(other) => panic!("unexpected result {other:?}"),
            Err(e) => return (last, e),
        }
    }
    panic!("{seq} never ran out");
}

/// Whether a rolled-back `ALTER SEQUENCE` stays in force is the engine's business; however the
/// engine and the catalog row come to disagree, a sequence that runs out is reported as `2200H`,
/// and the message never names a bound the sequence did not stop at.
#[test]
fn exhaustion_is_the_engines_verdict_and_never_names_a_wrong_bound() {
    let engine = BtreeEngine::new();
    let mut s = Session::new(&engine);
    for (seq, created, altered) in [("lowered", 10, 2), ("raised", 3, 10)] {
        ok(
            &mut s,
            &engine,
            &format!("CREATE SEQUENCE {seq} MAXVALUE {created}"),
        );
        ok(&mut s, &engine, "BEGIN");
        ok(
            &mut s,
            &engine,
            &format!("ALTER SEQUENCE {seq} MAXVALUE {altered}"),
        );
        ok(&mut s, &engine, "ROLLBACK");
        let (last, err) = draw_until_refused(&mut s, &engine, seq);
        assert_eq!(err.sqlstate(), "2200H", "{seq}: {err}");
        let named = format!("nextval: reached maximum value of sequence \"{seq}\" ({last})");
        let unnamed = format!("nextval: reached the limit of sequence \"{seq}\"");
        let message = err.to_string();
        assert!(
            message == named || message == unnamed,
            "{seq} stopped at {last}: {message}"
        );
    }
}

#[test]
fn widening_an_identity_column_lifts_its_bound_and_a_rollback_restores_it() {
    let engine = BtreeEngine::new();
    let mut s = Session::new(&engine);
    ok(
        &mut s,
        &engine,
        "CREATE TABLE w (id INT GENERATED ALWAYS AS IDENTITY, v INT)",
    );
    ok(&mut s, &engine, "SELECT setval('w_id_seq', 2147483646)");
    ok(&mut s, &engine, "INSERT INTO w (v) VALUES (1)");
    assert_eq!(
        code(&mut s, &engine, "INSERT INTO w (v) VALUES (2)"),
        "2200H"
    );
    ok(&mut s, &engine, "BEGIN");
    ok(&mut s, &engine, "ALTER TABLE w ALTER COLUMN id TYPE BIGINT");
    ok(&mut s, &engine, "ROLLBACK");
    assert_eq!(
        code(&mut s, &engine, "INSERT INTO w (v) VALUES (2)"),
        "2200H"
    );
    ok(&mut s, &engine, "ALTER TABLE w ALTER COLUMN id TYPE BIGINT");
    ok(&mut s, &engine, "INSERT INTO w (v) VALUES (2)");
    // The refused attempts did not move the sequence: no value was skipped.
    assert_eq!(int(&mut s, &engine, "SELECT max(id) FROM w"), 2_147_483_648);

    ok(
        &mut s,
        &engine,
        "CREATE TABLE n (id BIGINT GENERATED BY DEFAULT AS IDENTITY, v INT)",
    );
    ok(&mut s, &engine, "SELECT setval('n_id_seq', 3000000000)");
    assert_eq!(
        code(&mut s, &engine, "ALTER TABLE n ALTER COLUMN id TYPE INT"),
        "22023"
    );
}
