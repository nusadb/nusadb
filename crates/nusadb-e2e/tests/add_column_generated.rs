//! `ALTER TABLE ... ADD COLUMN ... GENERATED ALWAYS AS (expr) STORED`: existing rows are backfilled
//! with the computed value, later inserts and updates recompute it, an explicit value is refused,
//! and all of it holds for partitions and inheritance children and after a reopen. A column
//! `DEFAULT` added to a table outside `public` reaches later inserts too.

#![allow(
    clippy::expect_used,
    clippy::panic,
    reason = "integration test harness asserts by panicking on failure"
)]

use nusadb_btree::BtreeEngine;
use nusadb_core::{StorageEngine, TableSchema};
use nusadb_sql::ast::Value;
use nusadb_sql::{Catalog, Error, ExecutionResult, Session, analyze, parse, plan};

struct EngineCatalog<'a>(&'a dyn StorageEngine);

impl Catalog for EngineCatalog<'_> {
    fn lookup_table(&self, name: &str) -> Result<Option<TableSchema>, Error> {
        self.0.lookup_table(name).map_err(Into::into)
    }

    fn lookup_table_in(&self, schema: &str, name: &str) -> Result<Option<TableSchema>, Error> {
        self.0.lookup_table_in(schema, name).map_err(Into::into)
    }
}

fn run_try(engine: &BtreeEngine, sql: &str) -> Result<ExecutionResult, Error> {
    let logical = analyze(parse(sql)?, &EngineCatalog(engine))?;
    Session::new(engine).execute(plan(logical))
}

fn run(engine: &BtreeEngine, sql: &str) -> ExecutionResult {
    run_try(engine, sql).unwrap_or_else(|e| panic!("{sql}: {e}"))
}

fn ints(engine: &BtreeEngine, sql: &str) -> Vec<Vec<Option<i64>>> {
    match run(engine, sql) {
        ExecutionResult::Rows { rows, .. } => rows
            .into_iter()
            .map(|row| {
                row.into_iter()
                    .map(|v| match v {
                        Value::Int(n) => Some(n),
                        Value::Null => None,
                        other => panic!("expected an integer, got {other:?}"),
                    })
                    .collect()
            })
            .collect(),
        other => panic!("expected rows, got {other:?}"),
    }
}

fn code(engine: &BtreeEngine, sql: &str) -> &'static str {
    run_try(engine, sql).expect_err(sql).sqlstate()
}

fn row(values: &[i64]) -> Vec<Option<i64>> {
    values.iter().copied().map(Some).collect()
}

#[test]
fn existing_rows_are_backfilled_and_writes_recompute() {
    let engine = BtreeEngine::new();
    run(&engine, "CREATE TABLE t (id INT PRIMARY KEY, x INT)");
    run(&engine, "INSERT INTO t VALUES (1, 5), (2, 7)");
    run(
        &engine,
        "ALTER TABLE t ADD COLUMN g INT GENERATED ALWAYS AS (x * 2) STORED",
    );
    assert_eq!(
        ints(&engine, "SELECT id, x, g FROM t ORDER BY id"),
        vec![row(&[1, 5, 10]), row(&[2, 7, 14])]
    );
    run(&engine, "INSERT INTO t (id, x) VALUES (3, 9)");
    run(&engine, "UPDATE t SET x = 6 WHERE id = 1");
    assert_eq!(
        ints(&engine, "SELECT id, g FROM t ORDER BY id"),
        vec![row(&[1, 12]), row(&[2, 14]), row(&[3, 18])]
    );
    assert_eq!(code(&engine, "INSERT INTO t VALUES (4, 1, 1)"), "428C9");
    assert_eq!(code(&engine, "UPDATE t SET g = 3"), "428C9");
    // An index on the new column finds the backfilled values.
    run(&engine, "CREATE INDEX t_g ON t (g)");
    assert_eq!(
        ints(&engine, "SELECT id FROM t WHERE g = 14"),
        vec![row(&[2])]
    );
}

#[test]
fn what_cannot_be_added_is_refused_not_ignored() {
    let engine = BtreeEngine::new();
    run(&engine, "CREATE TABLE t (x INT)");
    run(&engine, "INSERT INTO t VALUES (6)");
    run(
        &engine,
        "ALTER TABLE t ADD COLUMN g INT GENERATED ALWAYS AS (x + 1) STORED",
    );
    for (sql, expected) in [
        // Reading another generated column, as at CREATE TABLE.
        (
            "ALTER TABLE t ADD COLUMN h INT GENERATED ALWAYS AS (g + 1) STORED",
            "42703",
        ),
        (
            "ALTER TABLE t ADD COLUMN h INT GENERATED ALWAYS AS (h + 1) STORED",
            "42703",
        ),
        (
            "ALTER TABLE t ADD COLUMN h INT GENERATED ALWAYS AS (x) VIRTUAL",
            "0A000",
        ),
        (
            "ALTER TABLE t ADD COLUMN h INT GENERATED ALWAYS AS (random()) STORED",
            "42P17",
        ),
        ("ALTER TABLE t ADD COLUMN h SERIAL", "0A000"),
        (
            "ALTER TABLE t ADD COLUMN h INT GENERATED ALWAYS AS IDENTITY",
            "0A000",
        ),
        (
            "ALTER TABLE t ADD COLUMN h INT GENERATED BY DEFAULT AS IDENTITY",
            "0A000",
        ),
        // NOT NULL is checked against the computed value of every existing row.
        (
            "ALTER TABLE t ADD COLUMN h INT NOT NULL GENERATED ALWAYS AS (NULLIF(x, 6)) STORED",
            "23502",
        ),
    ] {
        assert_eq!(code(&engine, sql), expected, "{sql}");
    }
    // Nothing of a refused statement is left behind.
    assert_eq!(ints(&engine, "SELECT * FROM t"), vec![row(&[6, 7])]);
}

#[test]
fn partitions_and_inheritance_children_get_the_column() {
    let engine = BtreeEngine::new();
    run(
        &engine,
        "CREATE TABLE p (k INT, v INT) PARTITION BY RANGE (k)",
    );
    run(
        &engine,
        "CREATE TABLE p1 PARTITION OF p FOR VALUES FROM (0) TO (10)",
    );
    run(
        &engine,
        "CREATE TABLE p2 PARTITION OF p FOR VALUES FROM (10) TO (20)",
    );
    run(&engine, "INSERT INTO p VALUES (1, 1), (15, 2)");
    run(
        &engine,
        "ALTER TABLE p ADD COLUMN g INT GENERATED ALWAYS AS (v * 10) STORED",
    );
    run(&engine, "INSERT INTO p (k, v) VALUES (2, 3), (16, 4)");
    run(&engine, "INSERT INTO p1 (k, v) VALUES (3, 5)");
    // Each partition holds its rows with the column computed (reads through the parent are
    // covered by the SQL logic test, whose catalog expands partitions).
    assert_eq!(
        ints(&engine, "SELECT k, g FROM p1 ORDER BY k"),
        vec![row(&[1, 10]), row(&[2, 30]), row(&[3, 50])]
    );
    assert_eq!(
        ints(&engine, "SELECT k, g FROM p2 ORDER BY k"),
        vec![row(&[15, 20]), row(&[16, 40])]
    );
    assert_eq!(code(&engine, "INSERT INTO p2 VALUES (17, 1, 1)"), "428C9");

    run(&engine, "CREATE TABLE parent (a INT)");
    run(&engine, "CREATE TABLE child (b INT) INHERITS (parent)");
    run(&engine, "INSERT INTO parent VALUES (1)");
    run(&engine, "INSERT INTO child VALUES (2, 20)");
    run(
        &engine,
        "ALTER TABLE parent ADD COLUMN g INT GENERATED ALWAYS AS (a + 1000) STORED",
    );
    run(&engine, "INSERT INTO child (a, b) VALUES (3, 30)");
    assert_eq!(
        ints(&engine, "SELECT a, g FROM ONLY parent ORDER BY a"),
        vec![row(&[1, 1001])]
    );
    assert_eq!(
        ints(&engine, "SELECT a, b, g FROM child ORDER BY a"),
        vec![row(&[2, 20, 1002]), row(&[3, 30, 1003])]
    );
}

#[test]
fn a_default_added_outside_public_reaches_later_inserts() {
    let engine = BtreeEngine::new();
    run(&engine, "CREATE SCHEMA app");
    run(&engine, "CREATE TABLE app.d (x INT)");
    run(&engine, "INSERT INTO app.d VALUES (1)");
    run(&engine, "ALTER TABLE app.d ADD COLUMN y INT DEFAULT 7");
    run(
        &engine,
        "ALTER TABLE app.d ADD COLUMN z INT GENERATED ALWAYS AS (x + 100) STORED",
    );
    run(&engine, "INSERT INTO app.d (x) VALUES (2)");
    assert_eq!(
        ints(&engine, "SELECT x, y, z FROM app.d ORDER BY x"),
        vec![row(&[1, 7, 101]), row(&[2, 7, 102])]
    );
}

#[test]
fn the_added_column_survives_a_reopen() {
    let dir = tempfile::tempdir().expect("tempdir");
    let path = dir.path().join("data");
    {
        let engine = BtreeEngine::open(&path).expect("open");
        run(&engine, "CREATE TABLE t (id INT PRIMARY KEY, x INT)");
        run(&engine, "INSERT INTO t VALUES (1, 5)");
        run(
            &engine,
            "ALTER TABLE t ADD COLUMN g INT GENERATED ALWAYS AS (x * 2) STORED",
        );
    }
    let engine = BtreeEngine::open(&path).expect("reopen");
    run(&engine, "INSERT INTO t (id, x) VALUES (2, 8)");
    run(&engine, "UPDATE t SET x = 6 WHERE id = 1");
    assert_eq!(
        ints(&engine, "SELECT id, g FROM t ORDER BY id"),
        vec![row(&[1, 12]), row(&[2, 16])]
    );
    assert_eq!(code(&engine, "INSERT INTO t VALUES (3, 1, 1)"), "428C9");
}
