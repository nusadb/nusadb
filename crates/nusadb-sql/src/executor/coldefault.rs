//! Column `DEFAULT` persistence + `SERIAL` columns.
//!
//! A column default is the expression used to fill a column omitted from an `INSERT`. Defaults live
//! in an engine-scoped SQL-layer catalog `nusadb_column_defaults`, mirroring the trigger/view catalog
//! pattern — the storage treaty deliberately has no column-default slot (see the note in
//! `nusadb_core::engine`), so they stay in the SQL layer. Created lazily; no treaty change.
//!
//! The default's canonical SQL text is stored per `(table, column)` and re-parsed at insert time into
//! a typed expression evaluated against an empty row (a default references no other column).
//!
//! A `SERIAL` column reuses the same catalog: its "default" is a [`SERIAL_PREFIX`] sentinel carrying
//! its backing sequence name, which the insert path resolves to a `nextval` ([`ColumnFill::Serial`])
//! rather than a pure expression — the sequence advance needs the engine, which a `DEFAULT`
//! expression's row-only evaluation does not have.
#![allow(clippy::wildcard_imports)]
#![allow(
    clippy::redundant_pub_crate,
    reason = "serial_default_sql / sequence_name are pub(crate) so the analyzer can build the \
              SERIAL sentinel; the module stays crate-private"
)]

use super::*;

/// Engine-scoped catalog of column defaults. Three text columns: `(table, column, default_sql)`.
const DEFAULT_CATALOG: &str = "nusadb_column_defaults";

/// The three-text-column schema of [`DEFAULT_CATALOG`].
const DEFAULT_CATALOG_SCHEMA: [ColumnType; 3] =
    [ColumnType::Text, ColumnType::Text, ColumnType::Text];

/// Prefix marking a stored "default" that is actually a `SERIAL` column's backing sequence rather
/// than an SQL expression. The remainder is the sequence name. Chosen to never collide with
/// real SQL (a leading NUL is not a valid default expression).
const SERIAL_PREFIX: &str = "\u{0}serial:";

/// Like [`SERIAL_PREFIX`], but for a `GENERATED ALWAYS AS IDENTITY` column (#9a). It still
/// auto-fills from its backing sequence when omitted, but — unlike `SERIAL` / `GENERATED BY DEFAULT` —
/// it rejects an explicit value at `INSERT`.
const IDENTITY_ALWAYS_PREFIX: &str = "\u{0}identity_always:";

/// Prefix marking a stored "default" that is actually a `GENERATED ALWAYS AS (<expr>) STORED` computed
/// column. The remainder is the generation expression's SQL text, which — unlike a `DEFAULT` —
/// references this table's other columns, so it is analyzed against the table scope and re-evaluated
/// against each fully-populated row. Always applied (and an explicit value for the column is rejected).
const GENERATED_PREFIX: &str = "\u{0}generated:";

/// The catalog default-text for a `GENERATED ALWAYS AS (<expr>) STORED` column.
#[must_use]
pub(crate) fn generated_default_sql(expr_sql: &str) -> String {
    format!("{GENERATED_PREFIX}{expr_sql}")
}

/// If `default_sql` marks a generated column, its generation-expression SQL; otherwise `None`.
pub(super) fn generated_expr(default_sql: &str) -> Option<&str> {
    default_sql.strip_prefix(GENERATED_PREFIX)
}

/// If `default_sql` is specifically a `GENERATED ALWAYS AS IDENTITY` sentinel, the backing sequence
/// name; otherwise `None`. Distinguishes the always-identity class (which `LIKE ... INCLUDING
/// IDENTITY` copies with a fresh sequence) from the `SERIAL` / by-default sentinel (which
/// `INCLUDING DEFAULTS` copies verbatim, sharing the source's sequence).
pub(super) fn identity_always_sequence(default_sql: &str) -> Option<&str> {
    default_sql.strip_prefix(IDENTITY_ALWAYS_PREFIX)
}

/// The column ordinals of `table`'s STORED generated columns. Their stored values are recomputed
/// from other columns on every write ([`column_fills`] → `ColumnFill::Generated`), so an `UPDATE`
/// that assigns a generated column's dependency changes the generated column even though it is not
/// in the assignment list. A caller reasoning about which columns an UPDATE can change (uniqueness /
/// index maintenance) must fold these in whenever anything is assigned, or it will wrongly treat a
/// generated key/index column as untouched.
pub(super) fn generated_column_ordinals(
    table: &TableSchema,
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<Vec<usize>, Error> {
    let stored = load_defaults(&catalog_key(&table.schema, &table.name), engine, txn)?;
    let mut ordinals = Vec::new();
    for (column, sql) in stored {
        if generated_expr(&sql).is_some()
            && let Some((index, _)) = table
                .columns
                .iter()
                .enumerate()
                .find(|(_, c)| c.name == column)
        {
            ordinals.push(index);
        }
    }
    Ok(ordinals)
}

/// The catalog default-text for a `SERIAL` / `GENERATED BY DEFAULT AS IDENTITY` column backed by
/// sequence `seq` (an explicit value is accepted).
#[must_use]
pub(crate) fn serial_default_sql(seq: &str) -> String {
    format!("{SERIAL_PREFIX}{seq}")
}

/// The catalog default-text for a `GENERATED ALWAYS AS IDENTITY` column backed by sequence `seq` (an
/// explicit value is rejected — #9a).
#[must_use]
pub(crate) fn identity_always_default_sql(seq: &str) -> String {
    format!("{IDENTITY_ALWAYS_PREFIX}{seq}")
}

/// The deterministic backing-sequence name for `table.column`'s `SERIAL`.
#[must_use]
pub(crate) fn sequence_name(table: &str, column: &str) -> String {
    format!("{table}_{column}_seq")
}

/// The `nusadb_column_defaults` row key for a table. The default catalog is keyed by table
/// name only, so a non-`public` schema must be folded into the key to keep two same-named tables in
/// different schemas from overwriting each other's defaults. `public` keeps the bare name so existing
/// rows (and the `public`-only paths: `ALTER ... SET DEFAULT`, SERIAL) are byte-for-byte unchanged.
#[must_use]
pub(super) fn catalog_key(schema: &str, name: &str) -> String {
    if schema == nusadb_core::PUBLIC_SCHEMA {
        name.to_owned()
    } else {
        format!("{schema}.{name}")
    }
}

/// If `default_sql` is a `SERIAL` / `GENERATED ... AS IDENTITY` sentinel (either variant), the backing
/// sequence name; otherwise `None`. Both variants auto-fill from the sequence when the column is
/// omitted — they differ only in whether an *explicit* value is allowed.
pub(super) fn serial_sequence(default_sql: &str) -> Option<&str> {
    default_sql
        .strip_prefix(SERIAL_PREFIX)
        .or_else(|| default_sql.strip_prefix(IDENTITY_ALWAYS_PREFIX))
}

/// How an omitted column is filled on `INSERT`: either by evaluating a `DEFAULT` expression, or by
/// advancing a `SERIAL` column's backing sequence.
pub(super) enum ColumnFill {
    /// Evaluate this typed `DEFAULT` expression per row.
    Expr(crate::planner::TypedExpr),
    /// Advance this sequence (`nextval`) for each row. `always` marks a `GENERATED ALWAYS AS IDENTITY`
    /// column, which rejects an explicit value (#9a).
    Serial {
        id: nusadb_core::SequenceId,
        always: bool,
    },
    /// Evaluate this `GENERATED ALWAYS AS (<expr>) STORED` expression against the fully-populated row
    /// (it references the row's other columns), in a second pass after every other column is filled.
    /// Always applied; an explicit value for the column is rejected at INSERT/UPDATE.
    Generated(crate::planner::TypedExpr),
}

/// The catalog row that records that every default in [`DEFAULT_CATALOG`] is filed under its
/// table's [`catalog_key`]: written when this build creates the catalog, and by
/// [`repair_misfiled_column_defaults`] once it has repaired a catalog an older build wrote. Its
/// table key starts with a NUL, which no default lookup is ever made with.
const KEYED_BY_SCHEMA_MARKER: (&str, &str, &str) = ("\u{0}catalog", "keyed_by_schema", "1");

/// The [`DEFAULT_CATALOG`] row for [`KEYED_BY_SCHEMA_MARKER`], encoded.
fn marker_row() -> Result<Vec<u8>, Error> {
    let (table, column, value) = KEYED_BY_SCHEMA_MARKER;
    row::encode(
        &[
            ast::Value::Text(table.to_owned()),
            ast::Value::Text(column.to_owned()),
            ast::Value::Text(value.to_owned()),
        ],
        &DEFAULT_CATALOG_SCHEMA,
    )
}

/// Look up the column-default catalog, creating it lazily if it does not exist yet.
fn ensure_default_catalog(
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<nusadb_core::TableId, Error> {
    if let Some(schema) = engine.lookup_table_as_of(txn, DEFAULT_CATALOG)? {
        return Ok(schema.id);
    }
    let columns = ["table", "column", "default_sql"]
        .into_iter()
        .map(|name| ColumnDef {
            name: name.to_owned(),
            ty: ColumnType::Text,
            nullable: false,
        })
        .collect();
    let def = TableDef {
        schema: "public".to_owned(),
        name: DEFAULT_CATALOG.to_owned(),
        columns,
    };
    let id = engine.create_table(txn, &def)?;
    // A catalog this build creates never holds a misfiled default, so mark it as already repaired.
    engine.insert(txn, id, &marker_row()?)?;
    Ok(id)
}

/// Persist `defaults` (each `(column, default SQL)`) for `table`, first removing any prior rows for it
/// so a recreated table does not inherit stale defaults. A no-op when `defaults` is empty and
/// the catalog does not exist yet.
pub(super) fn store_defaults(
    table: &str,
    defaults: &[(String, String)],
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<(), Error> {
    if defaults.is_empty() {
        // Nothing to add; only clear stale rows if the catalog already exists.
        delete_defaults_for_table(table, engine, txn)?;
        return Ok(());
    }
    let cat = ensure_default_catalog(engine, txn)?;
    delete_defaults_for_table(table, engine, txn)?;
    for (column, sql) in defaults {
        let row = [
            ast::Value::Text(table.to_owned()),
            ast::Value::Text(column.clone()),
            ast::Value::Text(sql.clone()),
        ];
        engine.insert(txn, cat, &row::encode(&row, &DEFAULT_CATALOG_SCHEMA)?)?;
    }
    Ok(())
}

/// `ALTER COLUMN … SET DEFAULT <expr>`: upsert one column's default, replacing any prior
/// default for that `(table, column)`.
pub(super) fn set_default(
    table: &str,
    column: &str,
    default_sql: &str,
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<(), Error> {
    let cat = ensure_default_catalog(engine, txn)?;
    delete_one(table, column, engine, txn)?;
    let row = [
        ast::Value::Text(table.to_owned()),
        ast::Value::Text(column.to_owned()),
        ast::Value::Text(default_sql.to_owned()),
    ];
    engine.insert(txn, cat, &row::encode(&row, &DEFAULT_CATALOG_SCHEMA)?)?;
    Ok(())
}

/// `ALTER COLUMN … DROP DEFAULT`: remove one column's default (a no-op if it has none).
pub(super) fn drop_default(
    table: &str,
    column: &str,
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<(), Error> {
    delete_one(table, column, engine, txn)
}

/// Remove the single `(table, column)` default row, if present.
fn delete_one(
    table: &str,
    column: &str,
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<(), Error> {
    let Some(cat) = engine.lookup_table_as_of(txn, DEFAULT_CATALOG)? else {
        return Ok(());
    };
    let mut victims = Vec::new();
    let mut scan = engine.scan(txn, cat.id)?;
    while let Some((tid, bytes)) = scan.try_next()? {
        let row = row::decode(&bytes, &DEFAULT_CATALOG_SCHEMA)?;
        if matches!((row.first(), row.get(1)),
            (Some(ast::Value::Text(t)), Some(ast::Value::Text(c))) if t == table && c == column)
        {
            victims.push(tid);
        }
    }
    for tid in victims {
        engine.delete(txn, cat.id, tid)?;
    }
    Ok(())
}

/// Remove every column-default row for `table` (used on `DROP TABLE` and before re-persisting).
pub(super) fn delete_defaults_for_table(
    table: &str,
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<(), Error> {
    let Some(cat) = engine.lookup_table_as_of(txn, DEFAULT_CATALOG)? else {
        return Ok(());
    };
    let mut victims = Vec::new();
    let mut scan = engine.scan(txn, cat.id)?;
    while let Some((tid, bytes)) = scan.try_next()? {
        let row = row::decode(&bytes, &DEFAULT_CATALOG_SCHEMA)?;
        if matches!(row.first(), Some(ast::Value::Text(t)) if t == table) {
            victims.push(tid);
        }
    }
    for tid in victims {
        engine.delete(txn, cat.id, tid)?;
    }
    Ok(())
}

/// `ALTER TABLE … RENAME TO`: re-file every default of `old` (a catalog key) under `new`, so the
/// renamed table keeps its `DEFAULT` / `SERIAL` / `IDENTITY` / `GENERATED` columns and a later
/// table taking the old name starts with none.
pub(super) fn rename_defaults_for_table(
    old: &str,
    new: &str,
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<(), Error> {
    let defaults = load_defaults(old, engine, txn)?;
    if defaults.is_empty() {
        return Ok(());
    }
    delete_defaults_for_table(old, engine, txn)?;
    for (column, sql) in defaults {
        set_default(new, &column, &sql, engine, txn)?;
    }
    Ok(())
}

/// Drop the sequence `seq` that backed a `SERIAL` or identity column whose default was just
/// removed, unless another column's default still draws from it: a table made with `LIKE ...
/// INCLUDING DEFAULTS` shares its source's sequence, and a plain `DEFAULT nextval('seq')` names it. Without this the sequence outlives its
/// column, and a later table taking the same name fails to create its own. A sequence that is
/// already gone is a no-op. Transactional: a rollback brings the sequence back.
pub(super) fn drop_owned_sequence(
    seq: &str,
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<(), Error> {
    if let Some(cat) = engine.lookup_table_as_of(txn, DEFAULT_CATALOG)? {
        let mut scan = engine.scan(txn, cat.id)?;
        while let Some((_, bytes)) = scan.try_next()? {
            let row = row::decode(&bytes, &DEFAULT_CATALOG_SCHEMA)?;
            if let Some(ast::Value::Text(sql)) = row.get(2)
                && (serial_sequence(sql) == Some(seq) || names_sequence(sql, seq))
            {
                return Ok(());
            }
        }
    }
    if let Some(id) = engine.lookup_sequence(seq)? {
        engine.drop_sequence(txn, id)?;
        super::seqcatalog::remove(engine, txn, seq)?;
        super::object_schema::forget(engine, txn, super::object_schema::SEQUENCE, seq)?;
        super::comment::forget(engine, txn, &super::comment::sequence_key(seq))?;
    }
    Ok(())
}

/// Whether the default expression `sql` names the sequence `seq` as a string literal, bare or
/// schema-qualified, the way `nextval('seq')` and `currval('app.seq')` do. Errs toward a match: a
/// sequence kept alive by a false match costs nothing, a dropped one breaks every insert.
fn names_sequence(sql: &str, seq: &str) -> bool {
    let (sql, seq) = (sql.to_lowercase(), seq.to_lowercase());
    sql.contains(&format!("'{seq}'")) || sql.contains(&format!(".{seq}'"))
}

/// Remove `column`'s default from the table filed under `table` (a [`catalog_key`]) and drop the
/// sequence it drew from when it was a `SERIAL` or identity column (see [`drop_owned_sequence`]).
pub(super) fn drop_default_and_sequence(
    table: &str,
    column: &str,
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<(), Error> {
    let owned = load_defaults(table, engine, txn)?
        .into_iter()
        .find(|(c, _)| c == column)
        .and_then(|(_, sql)| serial_sequence(&sql).map(str::to_owned));
    drop_default(table, column, engine, txn)?;
    if let Some(seq) = owned {
        drop_owned_sequence(&seq, engine, txn)?;
    }
    Ok(())
}

/// Remove every default of the table filed under `table` (a [`catalog_key`]) and drop the
/// sequences its `SERIAL` and identity columns drew from (see [`drop_owned_sequence`]).
pub(super) fn drop_defaults_and_sequences(
    table: &str,
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<(), Error> {
    let owned: Vec<String> = load_defaults(table, engine, txn)?
        .into_iter()
        .filter_map(|(_, sql)| serial_sequence(&sql).map(str::to_owned))
        .collect();
    delete_defaults_for_table(table, engine, txn)?;
    for seq in owned {
        drop_owned_sequence(&seq, engine, txn)?;
    }
    Ok(())
}

/// Load `table`'s defaults as `(column, default SQL)` pairs. The fast path (no catalog, or no default
/// for `table`) costs a single catalog lookup.
pub(super) fn load_defaults(
    table: &str,
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<Vec<(String, String)>, Error> {
    let Some(cat) = engine.lookup_table_as_of(txn, DEFAULT_CATALOG)? else {
        return Ok(Vec::new());
    };
    let mut out = Vec::new();
    let mut scan = engine.scan(txn, cat.id)?;
    while let Some((_, bytes)) = scan.try_next()? {
        let row = row::decode(&bytes, &DEFAULT_CATALOG_SCHEMA)?;
        if let (Some(ast::Value::Text(t)), Some(ast::Value::Text(col)), Some(ast::Value::Text(sql))) =
            (row.first(), row.get(1), row.get(2))
            && t == table
        {
            out.push((col.clone(), sql.clone()));
        }
    }
    Ok(out)
}

/// Build a per-column fill vector for `table`, indexed by column ordinal: `Some(fill)` for a column
/// with a `DEFAULT` or `SERIAL`, `None` otherwise. A regular default's SQL is re-parsed
/// and analyzed to the column's type; a serial sentinel resolves its backing sequence. Returns an
/// all-`None` vector when the table has neither.
pub(super) fn column_fills(
    table: &TableSchema,
    engine: &dyn StorageEngine,
    txn: TxnId,
) -> Result<Vec<Option<ColumnFill>>, Error> {
    let stored = load_defaults(&catalog_key(&table.schema, &table.name), engine, txn)?;
    let mut fills: Vec<Option<ColumnFill>> = (0..table.columns.len()).map(|_| None).collect();
    if stored.is_empty() {
        return Ok(fills);
    }
    for (column, sql) in stored {
        let Some((index, col)) = table
            .columns
            .iter()
            .enumerate()
            .find(|(_, c)| c.name == column)
        else {
            continue;
        };
        let fill = if let Some(gen_sql) = generated_expr(&sql) {
            // A generated column's expression references this table's other columns, so analyze it
            // against the table scope (not the empty default scope) and re-evaluate it per row.
            ColumnFill::Generated(crate::analyzer::analyze_generated_expr(
                gen_sql,
                table,
                col.ty,
                &super::dml::EmptyCatalog,
            )?)
        } else if let Some(seq) = serial_sequence(&sql) {
            let id = engine.lookup_sequence(seq)?.ok_or_else(|| {
                Error::Internal(format!(
                    "serial column \"{column}\" has no backing sequence"
                ))
            })?;
            ColumnFill::Serial {
                id,
                always: sql.starts_with(IDENTITY_ALWAYS_PREFIX),
            }
        } else {
            ColumnFill::Expr(crate::analyzer::analyze_default_expr(
                &sql,
                col.ty,
                &super::dml::EmptyCatalog,
            )?)
        };
        if let Some(slot) = fills.get_mut(index) {
            *slot = Some(fill);
        }
    }
    Ok(fills)
}

/// What [`repair_misfiled_column_defaults`] found and did.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct DefaultRepair {
    /// Whether the repair ran. `false` when the catalog was already repaired, was created by a
    /// build that files every default correctly, or does not exist.
    pub ran: bool,
    /// Each default moved to the table it belongs to, as `(schema, table, column)`.
    pub moved: Vec<(String, String, String)>,
    /// Each default left where it is because more than one table could own it.
    pub ambiguous: Vec<AmbiguousDefault>,
}

/// A default [`repair_misfiled_column_defaults`] could not attribute to one table.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AmbiguousDefault {
    /// The bare table name it is stored under.
    pub table: String,
    /// The column it is the default of.
    pub column: String,
    /// The default expression, as stored.
    pub default_sql: String,
    /// Every schema holding a table of that name with that column and no default of its own for
    /// it, `public` first when present (an insert into `public.<table>` uses the entry today).
    pub schemas: Vec<String>,
}

/// One row of [`DEFAULT_CATALOG`] as the repair reads it.
struct StoredDefault {
    tid: nusadb_core::engine::Tid,
    key: String,
    column: String,
    sql: String,
}

/// Move column defaults that an older build filed under a bare table name onto the table they
/// belong to, once per catalog.
///
/// Builds before this one stored the default of `ALTER TABLE s.t ADD COLUMN c ... DEFAULT ...` (and
/// earlier, of `ALTER TABLE s.t ALTER COLUMN c SET DEFAULT ...`) under the bare name `t` instead of
/// the key `s.t`. Inserts into `s.t` then missed the default, and a table `public.t` with a column
/// `c` picked it up. Nothing in the entry says which schema it came from, so ownership is decided
/// from the catalog as it stands:
///
/// - a bare entry `(t, c)` is moved to `s.t` when `s.t` is the only table named `t` outside
///   `public` that has a column `c` and no default of its own for it, and `public.t` either does not
///   exist or has no column `c`;
/// - when `public.t` has a column `c` as well, or several schemas qualify, the entry is left alone
///   and reported in [`DefaultRepair::ambiguous`]: it may be `public.t`'s own default, and guessing
///   wrong would move a default off the table it belongs to;
/// - an entry no table can own is left alone.
///
/// The moves and the marker that records the repair commit in one transaction, so a crash leaves
/// either the old catalog (and the repair runs again at the next open) or the repaired one. Run it
/// before any session uses the engine; the server does so when it opens a database. A standby
/// must not run it: it receives the primary's repair through the log.
///
/// # Errors
/// Propagates storage errors; the transaction is rolled back and nothing changes.
pub fn repair_misfiled_column_defaults(engine: &dyn StorageEngine) -> Result<DefaultRepair, Error> {
    let txn = engine.begin(IsolationLevel::default())?;
    match repair_in(engine, txn) {
        Ok(report) => {
            super::deferred::commit(engine, txn)?;
            Ok(report)
        },
        Err(e) => {
            // The original error is what the caller needs; a failed rollback changes nothing.
            let _ = super::deferred::rollback(engine, txn);
            Err(e)
        },
    }
}

/// The body of [`repair_misfiled_column_defaults`], inside `txn`.
fn repair_in(engine: &dyn StorageEngine, txn: TxnId) -> Result<DefaultRepair, Error> {
    let Some(cat) = engine.lookup_table_as_of(txn, DEFAULT_CATALOG)? else {
        return Ok(DefaultRepair::default());
    };
    let mut stored = Vec::new();
    let mut scan = engine.scan(txn, cat.id)?;
    while let Some((tid, bytes)) = scan.try_next()? {
        let row = row::decode(&bytes, &DEFAULT_CATALOG_SCHEMA)?;
        if let (
            Some(ast::Value::Text(key)),
            Some(ast::Value::Text(column)),
            Some(ast::Value::Text(sql)),
        ) = (row.first(), row.get(1), row.get(2))
        {
            stored.push(StoredDefault {
                tid,
                key: key.clone(),
                column: column.clone(),
                sql: sql.clone(),
            });
        }
    }
    drop(scan);
    let (marker_table, marker_column, _) = KEYED_BY_SCHEMA_MARKER;
    if stored
        .iter()
        .any(|d| d.key == marker_table && d.column == marker_column)
    {
        return Ok(DefaultRepair::default());
    }
    let filed: HashSet<(String, String)> = stored
        .iter()
        .map(|d| (d.key.clone(), d.column.clone()))
        .collect();
    // Every table by name, with the schemas it exists in and their columns.
    let mut tables: HashMap<String, Vec<(String, Vec<String>)>> = HashMap::new();
    for (schema, name) in engine.list_tables_qualified_as_of(txn)? {
        if let Some(table) = engine.lookup_table_as_of_in(txn, &schema, &name)? {
            let columns = table.columns.into_iter().map(|c| c.name).collect();
            tables.entry(name).or_default().push((schema, columns));
        }
    }
    let mut report = DefaultRepair {
        ran: true,
        ..DefaultRepair::default()
    };
    for entry in &stored {
        // A schema-qualified key, or the marker, is already where it belongs.
        let Some(same_named) = tables.get(&entry.key) else {
            continue;
        };
        let has_column = |columns: &[String]| columns.contains(&entry.column);
        let public_claims = same_named
            .iter()
            .any(|(schema, columns)| schema == nusadb_core::PUBLIC_SCHEMA && has_column(columns));
        let owners: Vec<&str> = same_named
            .iter()
            .filter(|(schema, columns)| {
                schema != nusadb_core::PUBLIC_SCHEMA
                    && has_column(columns)
                    && !filed.contains(&(catalog_key(schema, &entry.key), entry.column.clone()))
            })
            .map(|(schema, _)| schema.as_str())
            .collect();
        match (owners.as_slice(), public_claims) {
            ([], _) => {},
            ([schema], false) => {
                engine.delete(txn, cat.id, entry.tid)?;
                let row = [
                    ast::Value::Text(catalog_key(schema, &entry.key)),
                    ast::Value::Text(entry.column.clone()),
                    ast::Value::Text(entry.sql.clone()),
                ];
                engine.insert(txn, cat.id, &row::encode(&row, &DEFAULT_CATALOG_SCHEMA)?)?;
                report.moved.push((
                    (*schema).to_owned(),
                    entry.key.clone(),
                    entry.column.clone(),
                ));
            },
            (schemas, public_claims) => {
                let mut candidates: Vec<String> = schemas.iter().map(|s| (*s).to_owned()).collect();
                if public_claims {
                    candidates.insert(0, nusadb_core::PUBLIC_SCHEMA.to_owned());
                }
                report.ambiguous.push(AmbiguousDefault {
                    table: entry.key.clone(),
                    column: entry.column.clone(),
                    default_sql: entry.sql.clone(),
                    schemas: candidates,
                });
            },
        }
    }
    engine.insert(txn, cat.id, &marker_row()?)?;
    Ok(report)
}
